def say(lang, key, **values):
    """Fetch a sentence and fill in the blanks."""
    return T.get(lang, T["en"])[key].format(**values)


def join_list(lang, parts, word="and"):
    """['a', 'b', 'c'] -> 'a, b and c' (in the right language).
    Use word="or" for questions: 'a, b or c'."""
    joiner = T.get(lang, T["en"])[word]
    if len(parts) <= 1:
        return "".join(parts)
    return ", ".join(parts[:-1]) + joiner + parts[-1]
